#!/usr/bin/env node
// Lists the messages of @nginxui/plugin-market-ui in src/language/market.ts,
// so the extraction keeps them in the catalogs this app hands the
// marketplace views (see setMarketText in main.ts).

import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const ids = JSON.parse(readFileSync(require.resolve('@nginxui/plugin-market-ui/msgids.json'), 'utf8'))
const quote = id => `'${id.replace(/\\/g, '\\\\').replace(/'/g, '\\\'')}'`
const lines = ids.map(id => `  $gettext(${quote(id)}),`)
writeFileSync(new URL('../src/language/market.ts', import.meta.url), `// This file is auto-generated by scripts/market-messages.mjs. Do not edit manually.

export const marketMessages = [
${lines.join('\n')}
]
`)
