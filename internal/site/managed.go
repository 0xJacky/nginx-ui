package site

import (
	"errors"
	"path/filepath"
	"strings"

	"github.com/0xJacky/Nginx-UI/internal/config"
	"github.com/0xJacky/Nginx-UI/query"
	"github.com/uozi-tech/cosy"
	"gorm.io/gorm"
)

// managedByIngressPrefix is the model.Site.ManagedBy prefix of sites generated
// by an ingress. The ingress package owns the format; it is repeated here
// because that package builds on this one.
const managedByIngressPrefix = "ingress:"

// MutateOption adjusts a site mutation (save, rename, enable, disable, delete,
// maintenance).
type MutateOption func(*mutateOptions)

type mutateOptions struct {
	force bool
}

// Force lets a mutation change a site generated by an ingress. The ingress
// controller rewrites such a site on its next reconcile, so a forced change
// is temporary.
func Force(force bool) MutateOption {
	return func(o *mutateOptions) {
		o.force = force
	}
}

func resolveMutateOptions(opts []MutateOption) mutateOptions {
	var o mutateOptions
	for _, opt := range opts {
		if opt != nil {
			opt(&o)
		}
	}
	return o
}

// ManagedBy returns the ManagedBy value of the site row, or "" when the site
// has no row or is not managed.
func ManagedBy(name string) (string, error) {
	path, err := ResolveAvailablePath(name)
	if err != nil {
		return "", err
	}

	s := query.Site
	siteModel, err := s.Select(s.ManagedBy).Where(s.Path.Eq(path)).First()
	if errors.Is(err, gorm.ErrRecordNotFound) {
		return "", nil
	}
	if err != nil {
		return "", err
	}
	return siteModel.ManagedBy, nil
}

// CheckManaged returns ErrSiteManagedByIngress, carrying the ingress name, when
// the site is generated by an ingress and the change is not forced.
func CheckManaged(name string, opts ...MutateOption) error {
	if resolveMutateOptions(opts).force {
		return nil
	}

	managedBy, err := ManagedBy(name)
	if err != nil {
		return err
	}
	return ManagedError(managedBy)
}

// ManagedError returns ErrSiteManagedByIngress for a non-empty ManagedBy value
// and nil otherwise.
func ManagedError(managedBy string) error {
	if managedBy == "" {
		return nil
	}
	return cosy.WrapErrorWithParams(ErrSiteManagedByIngress, strings.TrimPrefix(managedBy, managedByIngressPrefix))
}

// CheckManagedPath applies CheckManaged to a config file path, for editors
// that work on files rather than sites. Paths outside sites-available and
// sites-enabled are never managed sites.
func CheckManagedPath(absPath string, opts ...MutateOption) error {
	dir := filepath.Clean(filepath.Dir(absPath))
	for _, siteDir := range []string{"sites-available", "sites-enabled"} {
		base, err := config.ResolveConfPath(siteDir)
		if err != nil {
			return err
		}
		if dir == filepath.Clean(base) {
			return CheckManaged(filepath.Base(absPath), opts...)
		}
	}
	return nil
}

// IsManagedByIngress reports whether err is ErrSiteManagedByIngress, with or
// without params.
func IsManagedByIngress(err error) bool {
	var cErr *cosy.Error
	if !errors.As(err, &cErr) {
		return false
	}
	var target *cosy.Error
	if !errors.As(ErrSiteManagedByIngress, &target) {
		return false
	}
	return cErr.Scope == target.Scope && cErr.Code == target.Code
}
